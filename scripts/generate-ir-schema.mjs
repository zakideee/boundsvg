import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const repositoryRoot = fileURLToPath(new URL("../", import.meta.url));
const generatedDirectory = fileURLToPath(
  new URL("../packages/core/src/generated/ir/", import.meta.url),
);
const structuralSchemaPath = `${generatedDirectory}structural-ir.schema.json`;
const inputSchemaPath = `${generatedDirectory}emit-ir-input.schema.json`;
const structuralTypesPath = `${generatedDirectory}structural-ir.ts`;
const validatorPath = `${generatedDirectory}structural-ir-validator.js`;
const validatorDeclarationPath = `${generatedDirectory}structural-ir-validator.d.ts`;
const metadataPath = `${generatedDirectory}generation.json`;

const STRUCTURAL_SCHEMA_ID = "https://github.com/zakideee/boundsvg/schemas/structural-ir-v1.json";
const INPUT_SCHEMA_ID = "https://github.com/zakideee/boundsvg/schemas/emit-ir-input-v1.json";
const GENERATED_BANNER =
  "// Generated by pnpm generate:ir-schema. Do not edit this file directly.\n";

function stableJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function stripValidatorAnnotations(value) {
  if (Array.isArray(value)) {
    return value.map(stripValidatorAnnotations);
  }
  if (value === null || typeof value !== "object") {
    return value;
  }
  return Object.fromEntries(
    Object.entries(value)
      .filter(([key]) => key !== "description" && key !== "title")
      .map(([key, nested]) => [key, stripValidatorAnnotations(nested)]),
  );
}

function generateRustSchemas() {
  const stdout = execFileSync(
    "cargo",
    ["run", "--quiet", "-p", "boundsvg", "--features", "ir-schema", "--bin", "generate_ir_schema"],
    {
      cwd: repositoryRoot,
      encoding: "utf8",
      maxBuffer: 4 * 1024 * 1024,
      stdio: ["ignore", "pipe", "inherit"],
    },
  );
  return JSON.parse(stdout);
}

function createValidator(schema) {
  const warnings = [];
  const validationSchema = stripValidatorAnnotations(schema);
  const ajv = new Ajv2020({
    allErrors: false,
    code: { esm: true, optimize: 2, source: true },
    // Keep small leaf schemas inline while sharing the recursive IR graph.
    // Ajv's boolean default expands this schema substantially when bundled.
    inlineRefs: 5,
    messages: false,
    logger: {
      log() {},
      warn(message) {
        warnings.push(String(message));
      },
      error(message) {
        warnings.push(String(message));
      },
    },
    strict: true,
  });
  ajv.addSchema(validationSchema, STRUCTURAL_SCHEMA_ID);
  const source = standaloneCode(ajv, { validateStructuralIr: STRUCTURAL_SCHEMA_ID });
  if (warnings.length > 0) {
    throw new Error(`Ajv schema compilation emitted diagnostics:\n${warnings.join("\n")}`);
  }
  return `${GENERATED_BANNER}${source}\n`;
}

async function generateArtifacts() {
  const rustSchemas = generateRustSchemas();
  const structuralSchema = {
    ...rustSchemas.structuralIr,
    $id: STRUCTURAL_SCHEMA_ID,
    title: "GeneratedStructuralIr",
  };
  const inputSchema = {
    ...rustSchemas.emitIrInput,
    $id: INPUT_SCHEMA_ID,
  };
  const structuralTypes = await compile(structuralSchema, "GeneratedStructuralIr", {
    additionalProperties: false,
    bannerComment: GENERATED_BANNER.trimEnd(),
    declareExternallyReferenced: true,
    enableConstEnums: false,
    format: true,
    strictIndexSignatures: false,
    unknownAny: false,
    unreachableDefinitions: false,
  });
  const validator = createValidator(structuralSchema);
  const validatorDeclaration = `${GENERATED_BANNER}import type { GeneratedStructuralIr } from "./structural-ir.js";

export type StructuralIrValidationError = {
  instancePath: string;
  schemaPath: string;
  keyword: string;
  params: Record<string, unknown>;
  message?: string;
};

export declare const validateStructuralIr: ((value: unknown) => value is GeneratedStructuralIr) & {
  errors?: readonly StructuralIrValidationError[] | null;
};
`;
  const metadata = {
    schemaGenerator: "schemars@1.2.2",
    typeGenerator: "json-schema-to-typescript@15.0.4",
    validatorGenerator: "ajv@8.20.0",
    validatorAnnotations: false,
    validatorInlineRefs: 5,
    validatorMessages: false,
    normalizationVersion: rustSchemas.normalizationVersion,
  };
  return new Map([
    [structuralSchemaPath, stableJson(structuralSchema)],
    [inputSchemaPath, stableJson(inputSchema)],
    [structuralTypesPath, structuralTypes],
    [validatorPath, validator],
    [validatorDeclarationPath, validatorDeclaration],
    [metadataPath, stableJson(metadata)],
  ]);
}

async function checkArtifacts(artifacts) {
  const stalePaths = [];
  for (const [path, content] of artifacts) {
    let current;
    try {
      current = await readFile(path, "utf8");
    } catch (error) {
      if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") {
        stalePaths.push(path);
        continue;
      }
      throw error;
    }
    if (current !== content) {
      stalePaths.push(path);
    }
  }
  if (stalePaths.length > 0) {
    throw new Error(
      `Generated IR schema artifacts are stale:\n${stalePaths
        .map((path) => `- ${path.slice(repositoryRoot.length)}`)
        .join("\n")}\nRun pnpm generate:ir-schema.`,
    );
  }
}

async function writeArtifacts(artifacts) {
  await mkdir(generatedDirectory, { recursive: true });
  for (const [path, content] of artifacts) {
    await writeFile(path, content);
  }
}

const artifacts = await generateArtifacts();
if (process.argv.includes("--check")) {
  await checkArtifacts(artifacts);
} else {
  await writeArtifacts(artifacts);
}
